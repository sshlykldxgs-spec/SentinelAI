import { chromium } from 'playwright'

const browser = await chromium.launch({ headless: true })
const errors = []

try {
  for (const viewport of [{ width: 1440, height: 900 }, { width: 390, height: 844 }]) {
    const page = await browser.newPage({ viewport, deviceScaleFactor: 1 })
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
    await page.getByText('决策情报总览').waitFor()
    await page.getByText('Meridian Electronics', { exact: true }).first().waitFor()
    const width = await page.evaluate(() => document.documentElement.scrollWidth)
    if (width > viewport.width) throw new Error(`Horizontal overflow at ${viewport.width}px: ${width}px`)
    await page.screenshot({ path: `/tmp/sentinelai-${viewport.width}.png`, fullPage: true })
    console.log(`${viewport.width}px overview: title and supplier data visible`)
    if (viewport.width === 1440) {
      await page.getByRole('button', { name: /启动多 Agent 分析/ }).click()
      await page.getByText('决策报告', { exact: true }).first().waitFor()
      await page.getByText('5 / 5').waitFor({ timeout: 15000 })
      await page.getByRole('button', { name: /Analyst Agent/ }).click()
      await page.getByText('Meridian Electronics').first().waitFor()
      await page.getByRole('button', { name: /Action Agent/ }).click()
      await page.getByText('逾期订单数', { exact: false }).first().waitFor()
      await page.evaluate(() => window.scrollTo(0, 0))
      await page.screenshot({ path: '/tmp/sentinelai-workflow.png', fullPage: true })
      console.log('workflow: five agents completed with grounded output')
      await page.getByRole('button', { name: /查看完整报告/ }).click()
      await page.getByRole('heading', { name: 'SentinelAI 决策情报报告' }).waitFor()
      const downloadEvent = page.waitForEvent('download')
      await page.getByRole('link', { name: /下载 Markdown/ }).click()
      const download = await downloadEvent
      if (download.suggestedFilename() !== 'sentinelai-report.md') throw new Error('Report filename mismatch')
      await page.screenshot({ path: '/tmp/sentinelai-report.png', fullPage: true })
      console.log('report: preview and Markdown download available')
      await page.getByRole('button', { name: '证据中心' }).click()
      await page.getByRole('heading', { name: '证据中心' }).waitFor()
      await page.getByRole('textbox', { name: '搜索证据' }).fill('Meridian')
      await page.locator('.evidence-item').first().waitFor()
      await page.screenshot({ path: '/tmp/sentinelai-evidence.png', fullPage: true })
      await page.getByRole('button', { name: /^待审批/ }).first().click()
      await page.locator('.approval-item').first().waitFor()
      await page.getByRole('textbox', { name: /审批意见/ }).first().fill('已核验演示证据，仅授权建议')
      await page.getByRole('button', { name: '批准', exact: true }).first().click()
      await page.locator('.approval-item').first().getByText('已批准', { exact: true }).waitFor()
      await page.screenshot({ path: '/tmp/sentinelai-approvals.png', fullPage: true })
      console.log('evidence search and backend-validated approval available')
      await page.getByRole('button', { name: '运行历史', exact: true }).click()
      await page.getByRole('heading', { name: '运行历史' }).waitFor()
      await page.getByRole('button', { name: '配置', exact: true }).click()
      await page.getByRole('heading', { name: '配置' }).waitFor()
      console.log('history and model settings available')
      await page.getByRole('button', { name: '总览', exact: true }).click()
      await page.getByRole('button', { name: 'Replay', exact: true }).click()
      await page.getByRole('button', { name: /启动多 Agent 分析/ }).click()
      await page.getByText('5 / 5').waitFor({ timeout: 15000 })
      await page.locator('.mode-badge[title="当前任务的实际执行模式"]').filter({ hasText: 'REPLAY' }).waitFor()
      await page.getByRole('button', { name: /查看完整报告/ }).click()
      await page.getByText('Replay / 离线测试回放，非在线推理', { exact: false }).first().waitFor()
      console.log('Replay mode explicitly labeled in task and report')
    } else {
      await page.locator('input[type="file"]').setInputFiles({
        name: 'new-notes.txt', mimeType: 'text/plain', buffer: Buffer.from('Additional evidence for review.'),
      })
      await page.locator('.files-list .file-row').filter({ hasText: 'new-notes.txt' }).first().waitFor()
      await page.getByRole('button', { name: '打开导航' }).click()
      await page.getByRole('button', { name: /Agent 工作流/ }).first().click()
      await page.getByRole('heading', { name: 'Agent 工作流' }).waitFor()
      await page.waitForFunction(() => !document.querySelector('.sidebar')?.classList.contains('sidebar-open'))
      await page.waitForTimeout(250)
      const mobileWidth = await page.evaluate(() => document.documentElement.scrollWidth)
      if (mobileWidth > viewport.width) throw new Error(`Workflow overflow on mobile: ${mobileWidth}px`)
      await page.screenshot({ path: '/tmp/sentinelai-mobile-workflow.png', fullPage: true })
      console.log('mobile: upload, navigation and workflow available')
      const direction = await page.locator('.pipeline').evaluate(element => getComputedStyle(element).display)
      if (direction !== 'grid') throw new Error('Mobile workflow must be vertical')
      for (const [label, heading] of [['证据中心', '证据中心'], ['决策报告', '决策报告'], ['待审批', '待审批'], ['运行历史', '运行历史'], ['配置', '配置']]) {
        await page.getByRole('button', { name: '打开导航' }).click()
        const target = label === '待审批' ? page.locator('.primary-nav button').filter({ hasText: label }) : page.getByRole('button', { name: label, exact: true }).first()
        await target.click()
        await page.getByRole('heading', { name: heading }).waitFor()
        await page.waitForFunction(() => !document.querySelector('.sidebar')?.classList.contains('sidebar-open'))
        await page.waitForTimeout(250)
        const sectionWidth = await page.evaluate(() => document.documentElement.scrollWidth)
        if (sectionWidth > viewport.width) throw new Error(`${label} overflows mobile: ${sectionWidth}px`)
      }
      await page.screenshot({ path: '/tmp/sentinelai-mobile-settings.png', fullPage: true })
      console.log('mobile: evidence, report, approvals, history and settings fit viewport')
    }
    await page.close()
  }
  const recovery = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  await recovery.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
  await recovery.getByRole('button', { name: /启动多 Agent 分析/ }).click()
  await recovery.locator('.timeline-event').first().waitFor()
  await recovery.context().setOffline(true)
  await recovery.waitForTimeout(1800)
  await recovery.context().setOffline(false)
  await recovery.getByText('5 / 5').waitFor({ timeout: 15000 })
  const ids = await recovery.locator('.timeline-event small').allTextContents()
  if (new Set(ids).size !== ids.length) throw new Error('Duplicate events after reconnect')
  const streamState = await recovery.locator('.telemetry-strip').textContent()
  if (!streamState.includes('执行结束')) throw new Error('Recovered stream did not receive terminal state')
  console.log('SSE offline/reconnect: terminal state recovered without duplicate events')
  await recovery.close()
  if (errors.length) throw new Error(`Browser errors: ${errors.join('; ')}`)
} finally {
  await browser.close()
}
